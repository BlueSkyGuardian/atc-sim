"""Airspace areas and pilot requests. (Aircraft live in aircraft.py.)"""
from __future__ import annotations

from dataclasses import dataclass, field
from typing import List, Optional, Tuple

from .geometry import Point, dist, point_in_polygon

# --- Airspace areas -----------------------------------------------------------
AREA_KINDS = {"danger": "D", "restricted": "R", "prohibited": "P"}


@dataclass
class Area:
    id: str
    name: str
    kind: str                         # danger | restricted | prohibited
    lower_fl: int
    upper_fl: int
    polygon: Optional[List[Point]] = None
    circle: Optional[Tuple[Point, float]] = None
    active: bool = False
    schedule: List[Tuple[float, bool]] = field(default_factory=list)   # (time, active)
    _sched_idx: int = 0

    def contains_xy(self, pt: Point) -> bool:
        if self.circle:
            c, r = self.circle
            return dist(c, pt) <= r
        return point_in_polygon(pt, self.polygon)

    def contains(self, pt: Point, alt_ft: float) -> bool:
        return self.lower_fl * 100 <= alt_ft <= self.upper_fl * 100 and self.contains_xy(pt)

    def advance(self, t: float) -> List[bool]:
        """Apply schedule events with time <= t. Returns list of new states applied."""
        changes = []
        while self._sched_idx < len(self.schedule) and self.schedule[self._sched_idx][0] <= t:
            new = self.schedule[self._sched_idx][1]
            self._sched_idx += 1
            if new != self.active:
                self.active = new
                changes.append(new)
        return changes

    def active_at(self, t: float) -> bool:
        """Activation state at a future time t (current state + published schedule)."""
        state = self.active
        for (ts, a) in self.schedule[self._sched_idx:]:
            if ts <= t:
                state = a
            else:
                break
        return state

    def next_change(self) -> Optional[dict]:
        for (ts, a) in self.schedule[self._sched_idx:]:
            if a != self.active:
                return {"time_s": ts, "active": a}
        return None

    def snapshot(self, t_now: float) -> dict:
        d = {
            "id": self.id,
            "name": self.name,
            "kind": self.kind,
            "designator": f"{AREA_KINDS[self.kind]}-{self.id}",
            "lower_fl": self.lower_fl,
            "upper_fl": self.upper_fl,
            "active": self.active,
            "next_change": self.next_change(),
            "published_schedule": [{"time_s": ts, "active": a} for ts, a in self.schedule],
        }
        if self.circle:
            d["shape"] = {"type": "circle", "center": list(self.circle[0]), "radius_nm": self.circle[1]}
        else:
            d["shape"] = {"type": "polygon", "points": [list(p) for p in self.polygon]}
        return d


# --- Pilot requests -----------------------------------------------------------
@dataclass
class Request:
    id: str
    callsign: str
    type: str                 # altitude | direct | speed | weather_deviation | report
    value: object
    reason: str
    time: float
    status: str = "pending"   # pending | approved | unable | amended | acknowledged | expired | cancelled
    origin: str = "scenario"  # scenario (scripted) | pilot (generated by weather / turbulence / top of descent)
    kind: Optional[str] = None  # "descent" for top-of-descent requests, "rvsm_unable" / "non_rvsm" for reports
    resolved_time: Optional[float] = None
    resolved_by: Optional[str] = None

    def phrase(self) -> str:
        if self.type == "weather_deviation":
            v = self.value
            return (f"{self.callsign} request heading {int(v['heading']):03d} for {v['distance_nm']} miles due weather, "
                    f"then direct {v['then_direct']}")
        if self.kind == "descent":
            return f"{self.callsign} request descent"
        if self.type == "report" and self.kind == "emergency":
            return str(self.value)                     # MAYDAY / PAN PAN: the callsign is inside the call
        if self.type == "report" and self.kind == "rvsm_unable":
            return f"{self.callsign} unable RVSM due {self.value}"
        if self.type == "report":
            return f"{self.callsign} {self.value}"
        return f"{self.callsign} requesting {self.what()}"

    def what(self) -> str:
        if self.type == "altitude":
            return f"FL{int(self.value)}"
        if self.type == "direct":
            return f"direct {self.value}"
        if self.type == "report":
            return "report (acknowledge with decision 'roger')"
        if self.type == "weather_deviation":
            v = self.value
            return f"weather deviation heading {int(v['heading']):03d} for {v['distance_nm']} miles"
        v = float(self.value)
        return f"Mach .{int(round(v * 100)):02d}" if v < 2 else f"{int(v)} knots"

    def snapshot(self) -> dict:
        return {
            "id": self.id, "callsign": self.callsign, "type": self.type, "value": self.value,
            "reason": self.reason, "time_s": self.time, "status": self.status,
            "resolved_time_s": self.resolved_time, "resolved_by": self.resolved_by,
            "phraseology": self.phrase(), "origin": self.origin, "kind": self.kind,
        }
